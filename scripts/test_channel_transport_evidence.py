#!/usr/bin/env python3
"""Adversarial mutations of the SAVED original native TCP + SQL observations.

The production source is the disposable GitHub Actions report generated by
run.py; tests mutate independent in-memory copies, never overwrite originals.
"""
from __future__ import annotations

import copy
import json
import os
from pathlib import Path
import unittest

from check_channel_transport import validate

SOURCE = Path(os.environ.get("CHANNELS_ORIGINAL_REPORT",
                            "lab/results/channels/original.json"))


class NativeEvidenceRefusal(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.source = json.loads(SOURCE.read_text(encoding="utf-8"))

    def altered(self, edit):
        data = copy.deepcopy(self.source)
        edit(data)
        problems = validate(data)
        self.assertTrue(problems, "Mutated original evidence silently accepted")

    def case(self, data, key):
        return next(row for row in data["cases"] if row["name"] == key)

    def test_01_original_14_case_live_evidence_is_valid(self):
        self.assertEqual(validate(self.source), [])

    def test_02_forged_global_success_rejected(self):
        self.altered(lambda d: d.update(status="PASS_WITH_UNVERIFIED_CASES"))

    def test_03_missing_native_case_rejected(self):
        self.altered(lambda d: d["cases"].pop())

    def test_04_false_physical_wan_pass_rejected(self):
        self.altered(lambda d: d["transport_scope"].update(real_eth_wan_partition=True))

    def test_05_false_production_bank_authorization_rejected(self):
        self.altered(lambda d: d["transport_scope"].update(production_approved=True))

    def test_06_pre_forward_drop_cannot_contact_core(self):
        self.altered(lambda d: self.case(d, "tcp-drop-before-forward")
                     ["transport_witness"].update(upstream_connected=True))

    def test_07_pre_forward_drop_cannot_have_postings(self):
        self.altered(lambda d: self.case(d, "tcp-drop-before-forward")
                     ["before_retry_snapshot"]["core"]["postings"].append({"op": "fake"}))

    def test_08_client_must_observe_response_loss(self):
        self.altered(lambda d: self.case(d, "tcp-drop-after-owner-response")
                     ["http"][0].update(client_status="COMMITTED"))

    def test_09_core_commit_must_precede_response_replay(self):
        self.altered(lambda d: self.case(d, "tcp-drop-after-owner-response")
                     ["before_retry_snapshot"]["core"]["operations"][0].update(state="AUTHORIZED"))

    def test_10_exactly_one_outbox_row_before_retry(self):
        self.altered(lambda d: self.case(d, "tcp-drop-after-owner-response")
                     ["before_retry_snapshot"]["core"]["outbox"].clear())

    def test_11_separately_read_sql_oracle_cannot_be_forged_failed(self):
        self.altered(lambda d: self.case(d, "tcp-delay-owner-response")
                     ["oracle_before_retry"].update(status="FAIL"))

    def test_12_idempotent_original_identity_is_required(self):
        self.altered(lambda d: self.case(d, "tcp-drop-after-owner-response")
                     ["http"][2]["response"].update(duplicate=False))

    def test_13_balance_mutation_is_detected_even_if_conserved(self):
        def edit(d):
            rows=self.case(d, "tcp-delay-owner-response")["snapshot"]["core"]["accounts"]
            rows[0]["balance"] += 9
            rows[1]["balance"] -= 9
        self.altered(edit)

    def test_14_duplicate_final_posting_is_rejected(self):
        self.altered(lambda d: self.case(d, "tcp-drop-after-owner-response")
                     ["snapshot"]["core"]["postings"].append(
                         copy.deepcopy(self.case(d,"tcp-drop-after-owner-response")
                                       ["snapshot"]["core"]["postings"][0])))

    def test_15_false_proxy_physical_network_claim_rejected(self):
        self.altered(lambda d: self.case(d, "tcp-delay-owner-response")
                     ["transport_witness"].update(physical_link_partition_tested=True))

    def test_16_proxy_must_have_processed_a_real_socket(self):
        self.altered(lambda d: self.case(d, "tcp-drop-before-forward")
                     ["transport_witness"].update(real_loopback_socket_used=False))

    def test_17_client_timeout_must_precede_delayed_response(self):
        self.altered(lambda d: self.case(d, "tcp-delay-owner-response")
                     ["transport_witness"].update(delay_seconds=0.01))

    def test_18_fail_closed_when_checkout_source_is_unrelated(self):
        original = os.environ.get("SOURCE_HEAD_SHA")
        try:
            os.environ["SOURCE_HEAD_SHA"] = "0000000000000000000000000000000000000000"
            self.assertTrue(validate(self.source))
        finally:
            if original is None:
                os.environ.pop("SOURCE_HEAD_SHA", None)
            else:
                os.environ["SOURCE_HEAD_SHA"] = original


    def test_19_missing_held_reply_race_rejected(self):
        self.altered(lambda d: self.case(d,"tcp-held-reply-concurrent-recovery")
                     .pop("held_recovery"))

    def test_20_old_reply_released_before_recovery_rejected(self):
        def edit(d):
            c=self.case(d,"tcp-held-reply-concurrent-recovery")
            c["transport_witness"]["response_release_monotonic_ns"] = (
                c["transport_witness"]["upstream_reply_seen_monotonic_ns"]+1)
        self.altered(edit)

    def test_21_fewer_than_eight_concurrent_replays_rejected(self):
        self.altered(lambda d: self.case(d,"tcp-held-reply-concurrent-recovery")
                     ["held_recovery"].update(replay_count=7))

    def test_22_one_duplicate_false_under_concurrency_rejected(self):
        self.altered(lambda d: self.case(d,"tcp-held-reply-concurrent-recovery")
                     ["held_recovery"]["replay_results"][4].update(duplicate=False))

    def test_23_forged_new_operation_id_during_replay_rejected(self):
        self.altered(lambda d: self.case(d,"tcp-held-reply-concurrent-recovery")
                     ["http"][3]["request"].update(operationId="new-fake-id"))

    def test_24_duplicate_posting_before_old_reply_released_rejected(self):
        def edit(d):
            c=self.case(d,"tcp-held-reply-concurrent-recovery")
            p=c["held_recovery"]["sql_before_old_ack"]["core"]["postings"]
            p.append(copy.deepcopy(p[0]))
        self.altered(edit)

    def test_25_conflicting_amount_attempt_must_be_rejected(self):
        self.altered(lambda d: self.case(d,"tcp-held-reply-concurrent-recovery")
                     ["http"][10]["response"].update(status="COMMITTED"))

    def test_26_forged_old_reply_timestamp_rejected(self):
        self.altered(lambda d: self.case(d,"tcp-held-reply-concurrent-recovery")
                     ["transport_witness"].update(release_signalled_monotonic_ns=-1))


if __name__ == "__main__":
    unittest.main()
