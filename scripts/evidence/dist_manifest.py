#!/usr/bin/env python3
"""Generate or verify docs/DIST_MANIFEST.md from the local, preserved evidence archives.

    python3 scripts/evidence/dist_manifest.py            # rewrite the manifest from evidence/archives/preserved-dist/
    python3 scripts/evidence/dist_manifest.py --verify   # fail if preserved archives and the manifest disagree

The payloads are not tracked (evidence/archives/preserved-dist/ is ignored). The manifest is tracked so a
reader who receives a copy of an archive can check its name, size, entry count and SHA-256
against the repository. Every archive must carry a receipt JSON whose digest matches the file;
a mismatching receipt fails verification (exit 1); a missing receipt or digest explicitly
marks verification incomplete (exit 2). Generation reports these states without certifying them.
Entry counts are receipt metadata, not a freshly verified ZIP inventory.
"""
import argparse
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIST = ROOT / "evidence" / "archives" / "preserved-dist"
MANIFEST = ROOT / "docs" / "DIST_MANIFEST.md"
HEADER = """# Delivery archives manifest

Generated by `scripts/evidence/dist_manifest.py`. The archives live in the ignored `evidence/archives/preserved-dist/`
folder and are **not** part of the repository; this table lets a reader verify a copy by
name, size and SHA-256. Every row cites the receipt JSON written at packaging time; the
`Receipt` column states whether the receipt digest matched the archive bytes when this
manifest was generated. An archive is evidence of *what was packaged*, not acceptance of
any experiment: see `docs/EVIDENCE.md` for statuses.

| Archive | Bytes | Entries | SHA-256 | Receipt |
|---|---:|---:|---|---|
"""


def sha256(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def rows():
    out = []
    for archive in sorted(DIST.glob("*.zip")):
        digest = sha256(archive)
        receipt = archive.with_suffix(".receipt.json")
        if not receipt.exists():
            receipt = archive.with_suffix(".json")
        recorded, entries = "", ""
        if receipt.exists():
            meta = json.loads(receipt.read_text(encoding="utf-8"))
            recorded = (meta.get("sha256") or meta.get("archiveSha256") or "").lower()
            entries = meta.get("entries") or meta.get("entryCount") or ""
            if isinstance(meta.get("files"), dict) and not entries:
                entries = len(meta["files"])
        status = "matches" if recorded == digest else ("no digest in receipt" if receipt.exists() and not recorded
                                                      else "MISMATCH" if receipt.exists() else "no receipt")
        out.append((archive.name, archive.stat().st_size, entries, digest,
                    f"`{receipt.name}` · {status}" if receipt.exists() else status))
    return out


def render() -> str:
    body = "".join(f"| `{n}` | {b:,} | {e} | `{d}` | {r} |\n" for n, b, e, d, r in rows())
    return HEADER + body


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--verify", action="store_true")
    args = parser.parse_args()
    if not DIST.is_dir():
        print("Preserved archive folder is absent; nothing to manifest", file=sys.stderr)
        return 2
    archive_rows = rows()
    text = render()
    if args.verify:
        mismatches = [row[0] for row in archive_rows if row[4].endswith(' · MISMATCH')]
        incomplete = [row[0] for row in archive_rows
                      if row[4] == 'no receipt' or row[4].endswith(' · no digest in receipt')]
        if mismatches:
            print('DIST MANIFEST: FAIL (receipt digest mismatch: ' + ', '.join(mismatches) + ')')
            return 1
        if incomplete or not archive_rows:
            print('DIST MANIFEST: INCOMPLETE (no receipt digest for: '
                  + (', '.join(incomplete) if incomplete else 'no archives') + ')')
            return 2
        if not MANIFEST.is_file() or MANIFEST.read_text(encoding="utf-8") != text:
            print("DIST MANIFEST: STALE (regenerate with scripts/evidence/dist_manifest.py)")
            return 1
        print("DIST MANIFEST: PASS")
        return 0
    MANIFEST.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {MANIFEST.relative_to(ROOT)} with {len(rows())} archives")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
